fn glyph(c: char) -> [u8; 7] {
    let up = c.to_ascii_uppercase();
    for (g, rows) in GLYPHS {
        if *g == up {
            return *rows;
        }
    }
    [0; 7]
}

/// Pixel width of `s` at the given scale (6px per char at scale 1).
pub fn text_width(s: &str, scale: u32) -> i32 {
    s.chars().count() as i32 * 6 * scale as i32
}

/// Draw text on any SDL canvas target. Pixels are filled rects.
pub fn draw_text<T: sdl2::render::RenderTarget>(
    canvas: &mut sdl2::render::Canvas<T>,
    mut x: i32,
    y: i32,
    s: &str,
    scale: u32,
    color: sdl2::pixels::Color,
) {
    canvas.set_draw_color(color);
    for c in s.chars() {
        let rows = glyph(c);
        for (ry, row) in rows.iter().enumerate() {
            for rx in 0..5 {
                if row & (1 << (4 - rx)) != 0 {
                    let _ = canvas.fill_rect(sdl2::rect::Rect::new(
                        x + rx as i32 * scale as i32,
                        y + ry as i32 * scale as i32,
                        scale,
                        scale,
                    ));
                }
            }
        }
        x += 6 * scale as i32;
    }
}
